//! The FIX dictionary generator, as a library (ADR-0207).
//!
//! One generator, three callers (ADR-0207 decision 1). It is loaded twice, the
//! way `fixbolt-sbe-gen` is (ADR-0081): by this crate's `build.rs` through
//! `#[path]`, to write the tables of [`crate::Fix44`] and, behind `fix50sp2`,
//! of the FIXT 1.1 / FIX 5.0 SP2 pair; and as this module, behind the
//! off-by-default `codegen` feature, for a user's own `build.rs`.
//!
//! - [`fix44_tables`] and `fixt11_fix50sp2_tables` (behind `fix50sp2`) are what `build.rs`
//!   writes to `$OUT_DIR/fix44.rs` and `$OUT_DIR/fixt11_fix50sp2.rs`, byte
//!   for byte (decision 2).
//! - [`generate`] is the user's door: an overlay onto the shipped FIX 4.4, or a
//!   whole FIX 4.4 file (decision 3), into one Rust file holding the user's own
//!   zero-sized type (decision 4). [`merged_model`] is the same merge without
//!   the writing: it answers what the generated type will answer, and reports
//!   the size of its tables.
//!
//! A user's `build.rs`, with `fixbolt-dict` as a build-dependency and the
//! `codegen` feature on:
//!
//! ```no_run
//! use fixbolt_dict::codegen::{self, Paths, Source};
//!
//! let overlay = std::fs::read_to_string("venue.xml")?;
//! let source = Source::Fix44Overlay(&overlay);
//! // Optional: a high custom tag widens every per-tag bitset; say so.
//! println!("cargo:warning={}", codegen::merged_model(source)?.table_size());
//! let rust = codegen::generate(source, "Venue", Paths::facade())?;
//! let out = std::path::PathBuf::from(std::env::var("OUT_DIR")?).join("venue.rs");
//! std::fs::write(out, rust)?;
//! println!("cargo:rerun-if-changed=venue.xml");
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! and in the crate, a module of its own — the file holds a format check, a
//! `tables` module (the free functions and statics the type answers from) and
//! the type with its two impls, and those names must not meet the crate's own:
//!
//! ```ignore
//! mod venue {
//!     include!(concat!(env!("OUT_DIR"), "/venue.rs"));
//! }
//! // venue::Venue implements Dictionary and Tables.
//! ```
//!
//! # The format check
//!
//! The build-dependency that writes the file and the dependency the file is
//! compiled against are two copies of `fixbolt-dict`, and nothing in cargo
//! makes them the same version. So the file opens with a compile-time check of
//! [`FORMAT_VERSION`] against the runtime crate's
//! (`tests/overlay.rs::the_generated_file_opens_with_its_format_check` holds
//! the emitted line to the text below). At the same format it compiles:
//!
//! ```
//! const _: () = assert!(
//!     ::fixbolt_dict::codegen_format::FORMAT_VERSION == 1,
//!     "Venue was generated by fixbolt-dict's codegen at format 1, and the fixbolt-dict it is compiled against reads another format: give the build-dependency and the dependency the same fixbolt version"
//! );
//! ```
//!
//! and a file written at another format does not — `E0080`, the constant's
//! evaluation failing on that sentence, not any other error:
//!
//! ```compile_fail,E0080
//! const _: () = assert!(
//!     ::fixbolt_dict::codegen_format::FORMAT_VERSION == 0,
//!     "Venue was generated by fixbolt-dict's codegen at format 0, and the fixbolt-dict it is compiled against reads another format: give the build-dependency and the dependency the same fixbolt version"
//! );
//! ```
//!
//! Where `build.rs` used to `die`, every function here returns a
//! [`GenError`]; nothing in this module panics, exits or indexes (CLAUDE.md §2
//! item 7). `parse` reads a document's fields and components, `merge` joins
//! two documents (the FIXT pair, or an overlay onto FIX 4.4), `model` holds
//! what one table is built from and computes it, `emit` writes it out.

